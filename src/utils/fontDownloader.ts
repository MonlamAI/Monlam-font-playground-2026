/**
 * Generates Google Fonts style embed code for selected fonts
 */
export function generateEmbedCode(fonts: FontItem[]): { html: string; css: string } {
  const fontNames = fonts.map((f) => f.name).join(', ');
  const html = `<!-- Monlam Fonts Web Embed -->\n<link rel="stylesheet" href="https://cdn.jsdelivr.net/gh/MonlamAI/monlam-font@main/public/fonts/monlam-fonts.css">\n<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Serif+Tibetan:wght@100..900&display=swap">`;

  const css = `/* Apply to your Tibetan text containers */\n.my-tibetan-content {\n  font-family: ${fonts.map((f) => `'${f.name}'`).join(', ')}, 'Noto Serif Tibetan', 'Jomolhari', serif;\n  text-rendering: optimizeLegibility;\n  -webkit-font-smoothing: antialiased;\n  font-feature-settings: "calt" 1, "ccmp" 1, "blws" 1, "abvs" 1, "psts" 1;\n  line-height: 1.85;\n}`;

  return { html, css };
}
