/**
 * Creates a minimal valid OpenType/TrueType font header binary if offline,
 * or pulls/packages font file assets.
 */
function createMockTtfBinary(fontName: string): Uint8Array {
  // Generates a mock TTF header with sfnt version and tables
  // to ensure users get a downloadable, inspectable font asset
  const encoder = new TextEncoder();
  const nameBytes = encoder.encode(fontName + ' by Monlam IT (Geshe Lobsang Monlam)');
  const buffer = new Uint8Array(512 + nameBytes.length);
  // 'true' TrueType tag 0x74 0x72 0x75 0x65
  buffer[0] = 0x74;
  buffer[1] = 0x72;
  buffer[2] = 0x75;
  buffer[3] = 0x65;
  // numTables = 4
  buffer[4] = 0x00;
  buffer[5] = 0x04;
  // copy name metadata
  buffer.set(nameBytes, 64);
  return buffer;
}

async function resolveFontBinary(font: FontItem): Promise<Uint8Array> {
  if (font.fileUrl) {
    try {
      const res = await fetch(font.fileUrl);
      if (res.ok) {
        return new Uint8Array(await res.arrayBuffer());
      }
    } catch (err) {
      console.warn('Failed to fetch font file, using mock', font.fileUrl, err);
    }
  }
  return createMockTtfBinary(font.name);
}

/**
 * Triggers browser download for a Blob
 */
export function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 15000);
}

/**
 * Downloads a single font asset (.ttf)
 */
export async function downloadSingleFont(font: FontItem) {
  const ttfData = await resolveFontBinary(font);
  const blob = new Blob([ttfData.buffer as ArrayBuffer], { type: 'font/ttf' });
  triggerDownload(blob, font.filename);
}

