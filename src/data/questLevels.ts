          'གངས་ཅན་ལྗོངས་ཀྱི་མཛེས་ལྗོངས་ནི། རི་བོ་མཐོ་ཞིང་ཆུ་བོ་གཙང་། མི་རྣམས་གཤིས་རྒྱུད་དྭངས་ཤིང་བཟང་།',
